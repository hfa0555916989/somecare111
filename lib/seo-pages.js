export function pageMeta(page) {
  return {
    title: { absolute: page.title },
    description: page.description,
    keywords: page.keywords,
    alternates: { canonical: page.path },
    robots: { index: true, follow: true },
    openGraph: {
      type: "article",
      locale: "ar_SA",
      url: page.path,
      title: page.title,
      description: page.description,
      images: [IMAGE],
    },
    twitter: { card: "summary_large_image", title: page.title, description: page.description, images: [IMAGE] },
  };
}

export function articleJsonLd(page) {
  const url = `${SITE_URL}${page.path}`;
  return {
    "@context": "https://schema.org",
    "@graph": [
      {
        "@type": "Article",
        headline: page.h1,
        description: page.description,
        inLanguage: "ar",
        datePublished: SEO_DATE,
        dateModified: SEO_DATE,
        mainEntityOfPage: url,
        image: [IMAGE],
        author: { "@type": "Person", name: "المطور حسن", url: `${SITE_URL}/` },
        publisher: { "@type": "Organization", name: "المطور حسن", url: `${SITE_URL}/`, logo: `${SITE_URL}/images/brand-logo.png` },
      },
      offerJsonLd(url),
      {
        "@type": "BreadcrumbList",
        itemListElement: [
          { "@type": "ListItem", position: 1, name: "الرئيسية", item: `${SITE_URL}/` },
          ...(page.kind === "post"
            ? [{ "@type": "ListItem", position: 2, name: "المدونة", item: `${SITE_URL}/blog` }, { "@type": "ListItem", position: 3, name: page.title, item: url }]
            : [{ "@type": "ListItem", position: 2, name: page.title, item: url }]),
        ],
      },
    ],
  };
}

